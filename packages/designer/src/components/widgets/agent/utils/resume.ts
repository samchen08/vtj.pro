/**
 * 续跑意图识别（纯函数）
 * 判定用户输入是否为"继续执行上一轮没完成的计划"类表述。
 * 命中后前端将其映射为断点恢复/失败重试（resumeLastRound / retryLastRound），
 * 而非新建 Architect 规划轮——修复"继续执行"时模型因无断点上下文而从头重复执行的问题。
 */
export function isResumeIntent(text: string): boolean {
  const t = text.trim();
  if (!t) return false;
  // 前缀必须是"继续/接着/恢复"
  if (!/^(继续|接着|恢复)/.test(t)) return false;
  // 必须携带续跑语义要素之一：
  // - 时间词（上一轮/上次/之前/刚才…）：明确指向已有轮次
  // - 完成类动词（完成/做完/执行完…，含"没/未"否定）：任务未完结
  // - 计划类名词（计划/任务/步骤/工作/进度…）：指向具体执行单元
  return (
    /(上一轮|上一|上次|之前|先前|刚才|上回)/.test(t) ||
    /(未|没)?(完成|做完|执行完)/.test(t) ||
    /(计划|任务|步骤|工作|进度|事项)/.test(t)
  );
}
